/**
 * 관광공사 원문의 연락처는 번호만 오지 않는다 — `"관리사무소 041-930-6883, 안내센터 041-930-6885"`,
 * `"031-310-2916, 2919~2920"`, `"043-532-3325/043-539-3605"` 처럼 안내문과 복수 번호가 섞여 온다
 * (api-specs/facility.md 참조). 이걸 그대로 `tel:`에 넣으면 유효한 URI가 아니라 전화가 안 걸린다.
 *
 * 그래서 걸 때는 첫 번째 번호만 쓰고, 화면에는 원문을 그대로 보여준다 — 안내센터가 따로 있는 경우
 * 사용자가 어디로 걸지 판단할 수 있어야 하기 때문이다.
 */

// 지역번호(0XX)·휴대폰(01X) / 대표번호(15XX·16XX·18XX). 하이픈은 있어도 없어도 잡는다.
const PHONE_RE = /(?:0\d{1,2}-?\d{3,4}-?\d{4}|1\d{3}-?\d{4})/;

/** 원문에서 걸 수 있는 첫 번째 번호만 뽑는다. 번호 형태가 없으면 null. */
export function primaryPhoneNumber(raw: string | null | undefined): string | null {
  if (!raw) return null;
  return raw.match(PHONE_RE)?.[0] ?? null;
}
