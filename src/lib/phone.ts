/**
 * 관광공사 원문의 연락처는 번호만 오지 않는다 — `"관리사무소 041-930-6883, 안내센터 041-930-6885"`,
 * `"031-310-2916, 2919~2920"`, `"043-532-3325/043-539-3605"` 처럼 안내문과 복수 번호가 섞여 온다
 * (api-specs/facility.md 참조). 이걸 그대로 `tel:`에 넣으면 유효한 URI가 아니라 전화가 안 걸린다.
 *
 * 그래서 걸 때는 첫 번째 번호만 쓰고, 화면에는 원문을 그대로 보여준다 — 안내센터가 따로 있는 경우
 * 사용자가 어디로 걸지 판단할 수 있어야 하기 때문이다.
 */

/**
 * 국번은 최대 **4자리**다. `0\d{1,2}`로 잡으면 050X 안심번호·0303 인터넷전화에서 위치 0의
 * 매칭이 실패하고, 스캐너가 두 번째 문자부터 다시 매칭해 앞 두 자리를 잘라먹는다
 * (`"0507-1234-5678"` → `"07-1234-5678"`). 없는 번호로 전화를 거는 셈이라 반드시 4자리까지 잡는다.
 *
 * 구분자는 하이픈뿐 아니라 점·공백·닫는 괄호도 받는다 — `"033.640.5420"`, `"02)123-4567"`,
 * `"033 640 5420"`이 실제로 온다. 걸 때는 숫자만 남겨 정규화한다.
 */
const PHONE_RE = /(?:0\d{1,3}[-.\s)]?\d{3,4}[-.\s]?\d{4}|1\d{3}[-.\s]?\d{4})/;

/**
 * 원문에서 걸 수 있는 첫 번째 번호를 `tel:`에 넣을 수 있는 형태(숫자만)로 뽑는다.
 * 번호 형태가 없으면 null — 이때 화면은 버튼을 감추되 **원문은 계속 보여줘야 한다**
 * (`+82-33-640-5420` 같은 표기는 못 잡지만, 사용자가 읽고 직접 걸 수는 있어야 한다).
 */
export function primaryPhoneNumber(raw: string | null | undefined): string | null {
  if (!raw) return null;
  const hit = raw.match(PHONE_RE)?.[0];
  return hit ? hit.replace(/\D/g, '') : null;
}
